create table if not exists public.server_listings (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 3 and 80),
  description text not null check (char_length(btrim(description)) between 20 and 1000),
  invite_code text not null unique check (invite_code ~ '^[A-Za-z0-9-]{2,64}$'),
  guild_id text not null check (guild_id ~ '^[0-9]{5,25}$'),
  guild_name text not null check (char_length(btrim(guild_name)) between 2 and 100),
  guild_icon_hash text,
  guild_banner_hash text,
  approximate_member_count integer check (approximate_member_count is null or approximate_member_count >= 0),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create index if not exists server_listings_approved_created_idx
  on public.server_listings (created_at desc)
  where status = 'approved';

alter table public.server_listings enable row level security;

drop policy if exists "Anyone can view approved server listings" on public.server_listings;
create policy "Anyone can view approved server listings"
  on public.server_listings for select
  to anon, authenticated
  using (status = 'approved');

drop policy if exists "Anyone can submit a server listing" on public.server_listings;
create policy "Anyone can submit a server listing"
  on public.server_listings for insert
  to anon, authenticated
  with check (status = 'pending');

grant select, insert on public.server_listings to anon, authenticated;
grant usage, select on sequence public.server_listings_id_seq to anon, authenticated;

